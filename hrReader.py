            #if format=="QE": assert self.norb%2==0, "format is set to QE, means we are doing soc case, but norb is odd"
            new_onsite=[0.]*self.norb

            totWaveVectors=int(data[2])
            iline=3
            recordedWaveVectors=0
            while(True):
                waveVectorPack=data[iline].split()
                recordedWaveVectors+=len(waveVectorPack)
                iline+=1
                if recordedWaveVectors>=totWaveVectors:break
            
            new_bondList=[]
            nTotal,nSkip=0,0
            while(True):
                lineinfo=data[iline].split()
                if len(lineinfo)==7:
                    R1, R2, R3, sourceID, targetID, t_real, t_imag = int(lineinfo[0]),int(lineinfo[1]),int(lineinfo[2]),int(lineinfo[3])-1,int(lineinfo[4])-1,float(lineinfo[5]),float(lineinfo[6])
                    t=t_real if ignoreImagPart else t_real + 1j*t_imag
                    if format=="QE":
                        sourceID=(sourceID%2)*(self.norb//2)+sourceID//2
                        targetID=(targetID%2)*(self.norb//2)+targetID//2
                    nTotal+=1
                    #if sourceID==targetID and sourceID==0: self.dRList.append(np.array([R1,R2,R3]))
                    if abs(t)>cutoff:
                        new_bondList.append(lat.BondDigital(sourceID,targetID,[R1,R2,R3],t))
                        #RxList.append(R1)
                        #RyList.append(R2)
                        #RzList.append(R3)
                        if R1==0 and R2 ==0 and R3==0 and sourceID==targetID:
                            new_onsite[sourceID]=t_real
                            assert t_imag<1e-4, 'found complex onsite energy on orb%d'%sourceID
                    else:
                        nSkip+=1
                iline+=1
                if iline>=len(data):break
            #print(self.bondList)
            #exit()
            #self.Rx_max, self.Rx_min, self.Ry_max, self.Ry_min, self.Rz_max, self.Rz_min= max(RxList),min(RxList),max(RyList),min(RyList),max(RzList),min(RzList)
            # data structure: bondInVecForm[Rx,Ry,Rz,source,target]=hopping
            new_bondInVecForm=np.zeros((self.Rx_max-self.Rx_min+1,self.Ry_max-self.Ry_min+1,self.Rz_max-self.Rz_min+1,self.norb,self.norb),dtype=complex)
            for bond in new_bondList:
                new_bondInVecForm[bond.overlat[0],bond.overlat[1],bond.overlat[2],bond.source,bond.target]=bond.t

            print('file %s has been successfully read in %.3fms, %d/%d skipped'%(filepath,1000*(time.time()-time0),nSkip,nTotal))
            return new_onsite, new_bondInVecForm