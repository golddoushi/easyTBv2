    def symmerizeBonds(self,atomicOrbIndexList,spinor=False,pgFilePath='',symOpSelection=[],atomicMagMomList=[]):
        def readSpinWFCSymOp(symRotateList,pgFilePath):
            dpgData=dPG.readInDoublePointGroupInfo(pgFilePath)
