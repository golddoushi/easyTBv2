    def adjustSOCStrength(self,socFactor=1):
        assert self.norb%2==0, 'num. of orbs is odd, inconsistent with SOC processing'
        halfOrb=self.norb//2
        bondList_updated=[]
        time0=time.time()
        for bond in self.bondList:
            # only analyze up-up
            if bond.source>=halfOrb or bond .target>=halfOrb: continue
            R1,R2,R3,s,t=bond.overlat[0],bond.overlat[1],bond.overlat[2],bond.source,bond.target
            t_uu=self.bondInVecForm[R1,R2,R3,s,t]
            t_dd=self.bondInVecForm[R1,R2,R3,s+halfOrb,t+halfOrb]
            t_ud=self.bondInVecForm[R1,R2,R3,s,t+halfOrb]
            t_du=self.bondInVecForm[R1,R2,R3,s+halfOrb,t]
            # calc soc interaction
            tz,ty,tx=(t_uu.imag-t_dd.imag)/2,(t_du.real-t_ud.real)/2,(t_ud.imag+t_du.imag)/2
            # flush hopping
            t_uu=t_uu.real+1j*tz*socFactor
            t_dd=t_dd.real-1j*tz*socFactor
            t_du=(1j*tx+ty)*socFactor
            t_ud=(1j*tx-ty)*socFactor
            
            bondList_updated.append(lat.BondDigital(s,t,bond.overlat,t_uu))
            bondList_updated.append(lat.BondDigital(s+halfOrb,t+halfOrb,bond.overlat,t_dd))
            bondList_updated.append(lat.BondDigital(s,t+halfOrb,bond.overlat,t_ud))
            bondList_updated.append(lat.BondDigital(s+halfOrb,t,bond.overlat,t_du))

            self.bondInVecForm[R1,R2,R3,s,t]=t_uu
            self.bondInVecForm[R1,R2,R3,s+halfOrb,t+halfOrb]=t_dd
            self.bondInVecForm[R1,R2,R3,s,t+halfOrb]=t_ud
            self.bondInVecForm[R1,R2,R3,s+halfOrb,t]=t_du
        self.bondList=bondList_updated
        print('SOC renormalized in %.3fs'%(time.time()-time0))
    
    def adjustInterLayerInteraction(self,layer1OrbList,layer2OrbList,factor=1.0):
        def checkIfInList(index,refList):
            for ref in refList:
                if ref>index: return False
                if ref==index: return True
            return False
        sort_list=np.argsort(layer1OrbList)
        layer1OrbList_sorted=[layer1OrbList[i] for i in sort_list]
        #sort_list=np.argsort(layer2OrbList)
        #layer2OrbList_sorted=[layer2OrbList[i] for i in sort_list]

        time0=time.time()
        bondList_updated=[]
        for bond in self.bondList:
            R1,R2,R3,s,t=bond.overlat[0],bond.overlat[1],bond.overlat[2],bond.source,bond.target
            s_in_layer1=checkIfInList(s,layer1OrbList_sorted)
            t_in_layer1=checkIfInList(t,layer1OrbList_sorted)

            s_signal=1 if s_in_layer1 else -1
            t_signal=1 if t_in_layer1 else -1
            t_updated=bond.t if s_signal*t_signal>0 else bond.t*factor
            bondList_updated.append(lat.BondDigital(s,t,bond.overlat,t_updated))
        self.bondList=bondList_updated
        print('layer interaction renormalized in %.3fs'%(time.time()-time0))

