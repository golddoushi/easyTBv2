            def pOrb(vec,format="w90"):
                '''p-orbitals defined in line with wannier90 v2.1
                   order: pz, px, py
                '''
                x,y,z=vec
                if format=="openmx":
                    return np.array([x,y,z])
                return np.array([z,x,y]) # in order: pz, px, py, 
            def dOrb(vec,format="w90"):
                '''d-orbitals defined in line with wannier90 v2.1
                   order: dz2, dxz, dyz, dx2-y2, dxy
                '''
                x,y,z=vec
                if format=="openmx":
                    return np.array([
                        sqrt(5/16)*(3*z*z-1),
                        sqrt(15/16)*(x*x-y*y),
                        sqrt(15/4)*x*y,
                        sqrt(15/4)*x*z,
                        sqrt(15/4)*y*z,
                    ])
                return np.array([
                    sqrt(5/16)*(3*z*z-1),
                    sqrt(15/4)*x*z,
                    sqrt(15/4)*y*z,
                    sqrt(15/16)*(x*x-y*y),
                    sqrt(15/16)*x*y*2
                ])
