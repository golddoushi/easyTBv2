        #self.toHome()
        
        # cutoff the hopping
        hopping_update=[]
        nhoppings=0
        ndropping=0
        for bond in self.bondList:
            if(abs(bond.overlat[cutDir])<1e-5):
                hopping_update.append(bond)
                nhoppings+=1
            else:
                ndropping+=1
                
        self.bondList=hopping_update
        #self.nhoppings=nhoppings
        print('dropping bonds:',ndropping)
        return ndropping

